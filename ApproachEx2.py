#program for Adding of Two Numbers by using Functions
#INPUT      : Taking Inside of Function Body
#PROCESS    : Done in Function Body
#RESULT     : Displayed in Function Body
#ApproachEx2.py
def addop():
    #Taking Input in Function Body
    a = float(input("Enter First Number:"))
    b = float(input("Enter Second Number:"))
    #Do the Process in Fucntion Body
    c=a+b
    # Display the Result in Function Body
    print("Sum({},{})={}".format(a,b,c))

#Main Program
addop()  # # Function Call without Input
